const BUILD_VERSION = "102a5d67e7719dfaa94e"; // Generated by scripts/prepare-offline.mjs
const SCOPE_URL = new URL(self.registration.scope);
const CACHE_PREFIX = `tabboz-mobile-${encodeURIComponent(SCOPE_URL.pathname)}-`;
const CACHE_NAME = `${CACHE_PREFIX}${BUILD_VERSION}`;
const INDEX_URL = new URL("index.html", SCOPE_URL).href;
const INVENTORY_URL = new URL("app/cache-assets.json", SCOPE_URL).href;

self.addEventListener("install", event => {
  event.waitUntil((async () => {
    const response = await fetch(INVENTORY_URL, { cache: "no-store" });
    if (!response.ok) throw new Error("Offline asset inventory is unavailable.");
    const inventory = await response.json();
    if (inventory.version !== BUILD_VERSION || !Array.isArray(inventory.assets)) {
      throw new Error("Offline asset inventory does not match this app version.");
    }
    const urls = inventory.assets.map(asset => {
      const url = new URL(asset, SCOPE_URL);
      if (url.origin !== SCOPE_URL.origin || !url.pathname.startsWith(SCOPE_URL.pathname)) {
        throw new Error("Offline asset is outside the app scope.");
      }
      return new Request(url.href, { cache: "reload" });
    });
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll(urls);
    await cache.put(INVENTORY_URL, new Response(JSON.stringify(inventory), {
      headers: { "Content-Type": "application/json" },
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== SCOPE_URL.origin || !url.pathname.startsWith(SCOPE_URL.pathname)) return;
  const appNavigation = request.mode === "navigate" &&
    (url.pathname === SCOPE_URL.pathname || url.pathname === new URL(INDEX_URL).pathname);
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request);
    try {
      const response = await fetch(request);
      // Only keep the prepared runtime inventory and navigations. Source files
      // inspected in a browser do not expand the offline package.
      if (response.status === 200 && (cached || appNavigation)) {
        await cache.put(request, response.clone()).catch(() => {});
      }
      return response;
    } catch (error) {
      if (cached) return cached;
      if (appNavigation) {
        const index = await cache.match(INDEX_URL);
        if (index) return index;
      }
      throw error;
    }
  })());
});
