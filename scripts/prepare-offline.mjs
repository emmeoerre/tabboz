import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const paths = new Set(["index.html", "manifest.webmanifest", "runtime/build/tabboz.js", "runtime/build/tabboz.wasm"]);
const resourceRules = [
  ["engine/resources/bitmaps", /\.(?:png|json)$/i],
  ["engine/resources/icons", /\.(?:png|gif|ico)$/i],
  ["engine/resources/wavs", /\.wav$/i],
  ["engine/resources/strings", /\.json$/i],
  ["engine/resources/menus", /\.json$/i],
  ["engine/resources/dialogs/includes", /\.inc\.html$/i],
  ["engine/resources/css", /\.(?:css|woff2?)$/i],
  ["engine/resources/js", /\.js$/i],
  ["app", /\.(?:js|css|png|svg)$/i],
];

async function collect(directory, pattern) {
  for (const entry of await readdir(path.join(root, directory), { withFileTypes: true })) {
    const relative = `${directory}/${entry.name}`;
    if (entry.isDirectory()) await collect(relative, pattern);
    else if (entry.isFile() && pattern.test(entry.name)) paths.add(relative);
  }
}

for (const [directory, pattern] of resourceRules) await collect(directory, pattern);
const assets = [...paths].sort();
const hash = createHash("sha256");
let bytes = 0;
for (const asset of assets) {
  const data = await readFile(path.join(root, asset));
  bytes += data.byteLength;
  hash.update(asset).update("\0").update(data).update("\0");
}
const version = hash.digest("hex").slice(0, 20);
const inventory = { version, assets };
await writeFile(path.join(root, "app/cache-assets.json"), `${JSON.stringify(inventory, null, 2)}\n`);
const workerPath = path.join(root, "service-worker.js");
const worker = await readFile(workerPath, "utf8");
const versionLine = /^const BUILD_VERSION = "[^"]+"; \/\/ Generated by scripts\/prepare-offline\.mjs$/m;
if (!versionLine.test(worker)) throw new Error("Service worker build-version marker is missing.");
await writeFile(workerPath, worker.replace(versionLine, `const BUILD_VERSION = "${version}"; // Generated by scripts/prepare-offline.mjs`));
console.log(`Prepared ${assets.length} offline assets (${(bytes / 1024 / 1024).toFixed(2)} MiB), version ${version}.`);
